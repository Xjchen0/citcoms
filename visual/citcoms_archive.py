"""
CitcomS ASCII Output Archive & Inode Governance Tool
===================================================

This tool provides single-file compression, verification, and automated cleanup
for fragmented ASCII output files generated by CitcomS simulations.

Key Features:
  - 100% Pure Standard Library (0 external dependencies, no numpy/scipy/pip needed).
  - Compatible with legacy cluster environments running Python 2.6/2.7 as well as Python 3.
  - Consolidates hundreds of per-step ASCII files into a single gzip-compressed archive
    (e.g. <datafile>.<step>.tar.gz), reducing file count from ~1000/step to 1/step.
  - Typical compression ratio: 75% ~ 85% storage reduction.
  - Safe integrity verification before any raw file cleanup (--clean).
  - One-click lossless extraction (--extract) when raw files are needed.

Usage Examples:
  # 1. Archive a single timestep:
  python visual/citcoms_archive.py -d /path/to/output -p mymodel -s 5000

  # 2. Archive and safely delete raw ASCII fragments (solves inode exhaustion):
  python visual/citcoms_archive.py -d /path/to/output -p mymodel -s 5000 --clean

  # 3. Archive all discovered timesteps:
  python visual/citcoms_archive.py -d /path/to/output -p mymodel --all --clean

  # 4. Automatically detect datadir and datafile from a CitcomS .cfg file:
  python visual/citcoms_archive.py -c /path/to/model.cfg --all --clean

  # 5. Extract an archived timestep back to raw ASCII files:
  python visual/citcoms_archive.py -d /path/to/output -p mymodel -s 5000 --extract

  # 6. Check directory file counts and storage status:
  python visual/citcoms_archive.py -d /path/to/output -p mymodel --status
"""

from __future__ import print_function

import os
import sys
import glob
import tarfile
import optparse


def parse_cfg_file(cfg_path):
    """Parse datadir and datafile from a CitcomS .cfg file without external dependencies."""
    params = {'datadir': '.', 'datafile': 'citcoms'}
    if not os.path.exists(cfg_path):
        return params

    try:
        with open(cfg_path, 'r') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#') or line.startswith('['):
                    continue
                line = line.split('#')[0].strip()
                if '=' in line:
                    key, val = line.split('=', 1)
                    key = key.strip()
                    val = val.strip().strip('"').strip("'")
                    if key in ('datadir', 'datafile'):
                        params[key] = val
    except Exception as e:
        print("Warning: Could not parse %s: %s" % (cfg_path, str(e)))

    # If datadir is relative, resolve relative to cfg file directory
    cfg_dir = os.path.dirname(os.path.abspath(cfg_path))
    if not os.path.isabs(params['datadir']):
        params['datadir'] = os.path.normpath(os.path.join(cfg_dir, params['datadir']))

    return params


def find_step_files(datadir, datafile, step):
    """Find all raw output files for a given timestep.
    Matches files starting with <datafile>. and ending with .<step>.
    Excludes .tar.gz, .h5, .vts, .vtm, .xdmf files.
    """
    pattern = os.path.join(datadir, "%s.*.%d" % (datafile, step))
    matched = glob.glob(pattern)

    # Also check if there's datafile.ave.<step> or datafile.geoid.<step>
    filtered = []
    excluded_exts = ('.tar.gz', '.tgz', '.zip', '.h5', '.vts', '.vtm', '.xdmf')
    for f in matched:
        base = os.path.basename(f)
        if any(base.endswith(ext) for ext in excluded_exts):
            continue
        filtered.append(f)

    return sorted(filtered)


def discover_all_steps(datadir, datafile):
    """Scan datadir for all available timesteps based on *.velo.*.<step> or *.ave.<step>."""
    pattern = os.path.join(datadir, "%s.velo.*" % datafile)
    candidates = glob.glob(pattern)
    if not candidates:
        pattern = os.path.join(datadir, "%s.*.*" % datafile)
        candidates = glob.glob(pattern)

    steps = set()
    for f in candidates:
        parts = os.path.basename(f).split('.')
        if len(parts) >= 3:
            last = parts[-1]
            if last.isdigit():
                steps.add(int(last))

    # Also check existing archives
    arch_pattern = os.path.join(datadir, "%s.*.tar.gz" % datafile)
    for f in glob.glob(arch_pattern):
        base = os.path.basename(f)
        name_no_ext = base[:-7]  # remove .tar.gz
        parts = name_no_ext.split('.')
        if len(parts) >= 2 and parts[-1].isdigit():
            steps.add(int(parts[-1]))

    return sorted(list(steps))


def archive_step(datadir, datafile, step, clean=False, verbose=True):
    """Consolidate all raw ASCII files of a timestep into <datafile>.<step>.tar.gz.
    Validates archive contents before cleaning raw files.
    """
    raw_files = find_step_files(datadir, datafile, step)
    if not raw_files:
        if verbose:
            print("[Step %d] No raw files found to archive." % step)
        return False

    archive_name = "%s.%d.tar.gz" % (datafile, step)
    archive_path = os.path.join(datadir, archive_name)
    temp_archive_path = archive_path + ".tmp"

    total_raw_bytes = sum(os.path.getsize(f) for f in raw_files)

    if verbose:
        print("[Step %d] Packaging %d files (%.2f MB)..." %
              (step, len(raw_files), total_raw_bytes / (1024.0 * 1024.0)))

    # Write tar.gz atomically via temp file
    try:
        tar = tarfile.open(temp_archive_path, "w:gz")
        for f in raw_files:
            arcname = os.path.basename(f)
            tar.add(f, arcname=arcname)
        tar.close()
    except Exception as e:
        if os.path.exists(temp_archive_path):
            os.remove(temp_archive_path)
        print("ERROR: Failed to create archive for step %d: %s" % (step, str(e)))
        return False

    # Verification: Read back members and check count
    try:
        check_tar = tarfile.open(temp_archive_path, "r:gz")
        members = check_tar.getnames()
        check_tar.close()
        if len(members) != len(raw_files):
            raise ValueError("Member count mismatch: expected %d, got %d" %
                             (len(raw_files), len(members)))
    except Exception as e:
        if os.path.exists(temp_archive_path):
            os.remove(temp_archive_path)
        print("ERROR: Verification failed for step %d: %s" % (step, str(e)))
        return False

    # Atomically replace final archive
    if os.path.exists(archive_path):
        os.remove(archive_path)
    os.rename(temp_archive_path, archive_path)

    arch_bytes = os.path.getsize(archive_path)
    ratio = (1.0 - float(arch_bytes) / float(max(1, total_raw_bytes))) * 100.0

    if verbose:
        print("  -> Saved: %s (%.2f MB, compressed %.1f%%)" %
              (archive_name, arch_bytes / (1024.0 * 1024.0), ratio))

    # Optional safe cleanup
    if clean:
        deleted_count = 0
        for f in raw_files:
            try:
                os.remove(f)
                deleted_count += 1
            except Exception as e:
                print("Warning: Failed to delete %s: %s" % (f, str(e)))
        if verbose:
            print("  -> Cleaned %d raw files. Inode pressure relieved." % deleted_count)

    return True


def extract_step(datadir, datafile, step, verbose=True):
    """Extract an archived timestep back to raw ASCII files in datadir."""
    archive_name = "%s.%d.tar.gz" % (datafile, step)
    archive_path = os.path.join(datadir, archive_name)

    if not os.path.exists(archive_path):
        print("ERROR: Archive %s not found." % archive_path)
        return False

    if verbose:
        print("[Step %d] Extracting %s to %s..." % (step, archive_name, datadir))

    try:
        tar = tarfile.open(archive_path, "r:gz")
        tar.extractall(path=datadir)
        tar.close()
        if verbose:
            print("  -> Successfully extracted step %d." % step)
        return True
    except Exception as e:
        print("ERROR: Failed to extract %s: %s" % (archive_path, str(e)))
        return False


def print_status(datadir, datafile):
    """Print the storage statistics: number of raw files vs archives."""
    all_steps = discover_all_steps(datadir, datafile)
    if not all_steps:
        print("No steps found in datadir '%s' with prefix '%s'." % (datadir, datafile))
        return

    print("======================================================================")
    print("CitcomS Output Governance Status: %s (%s)" % (datafile, datadir))
    print("======================================================================")
    total_raw_files = 0
    total_raw_bytes = 0
    archived_steps = 0
    unarchived_steps = 0

    for step in all_steps:
        raw_files = find_step_files(datadir, datafile, step)
        arch_file = os.path.join(datadir, "%s.%d.tar.gz" % (datafile, step))
        has_arch = os.path.exists(arch_file)

        if has_arch and not raw_files:
            archived_steps += 1
        else:
            unarchived_steps += 1
            total_raw_files += len(raw_files)
            total_raw_bytes += sum(os.path.getsize(f) for f in raw_files)

    print("Total detected steps   : %d (range: %d ~ %d)" %
          (len(all_steps), min(all_steps), max(all_steps)))
    print("Cleanly archived steps : %d" % archived_steps)
    print("Unarchived / raw steps : %d" % unarchived_steps)
    print("Outstanding raw files  : %d files (%.2f MB)" %
          (total_raw_files, total_raw_bytes / (1024.0 * 1024.0)))
    if total_raw_files > 0:
        print("Estimated inode saving if archived: ~%d files" % total_raw_files)
        print("Estimated disk saving if archived : ~%.2f MB" %
              (total_raw_bytes * 0.75 / (1024.0 * 1024.0)))
    print("======================================================================")


def main():
    parser = optparse.OptionParser(usage="usage: %prog [options]")
    parser.add_option("-d", "--datadir", dest="datadir", default=None,
                      help="Directory containing CitcomS output files")
    parser.add_option("-p", "--datafile", dest="datafile", default=None,
                      help="Prefix of CitcomS data files (e.g. stage1, zhu_EPSL)")
    parser.add_option("-c", "--cfg", dest="cfg", default=None,
                      help="CitcomS .cfg file to automatically extract datadir and datafile")
    parser.add_option("-s", "--step", dest="step", type="int", default=None,
                      help="Specific timestep to process")
    parser.add_option("--all", dest="all_steps", action="store_true", default=False,
                      help="Process all available timesteps")
    parser.add_option("--range", dest="range_args", nargs=3, type="int",
                      metavar="START END STRIDE", default=None,
                      help="Process a range of timesteps: START END STRIDE")
    parser.add_option("--clean", dest="clean", action="store_true", default=False,
                      help="Safely remove raw ASCII files after archive verification")
    parser.add_option("--extract", dest="extract", action="store_true", default=False,
                      help="Extract archived file(s) back to raw ASCII")
    parser.add_option("--status", dest="status", action="store_true", default=False,
                      help="Show summary of raw vs archived files and inode count")

    (options, args) = parser.parse_args()

    datadir = options.datadir
    datafile = options.datafile

    if options.cfg:
        cfg_params = parse_cfg_file(options.cfg)
        if not datadir:
            datadir = cfg_params.get('datadir', '.')
        if not datafile:
            datafile = cfg_params.get('datafile', 'citcoms')

    if not datadir:
        datadir = '.'
    if not datafile:
        datafile = 'citcoms'

    datadir = os.path.abspath(datadir)

    if options.status:
        print_status(datadir, datafile)
        return

    # Determine steps to process
    steps_to_process = []
    if options.step is not None:
        steps_to_process = [options.step]
    elif options.range_args:
        start, end, stride = options.range_args
        steps_to_process = list(range(start, end + 1, stride))
    elif options.all_steps:
        steps_to_process = discover_all_steps(datadir, datafile)
        if not steps_to_process:
            print("No timesteps found in %s with prefix %s" % (datadir, datafile))
            return
    else:
        print("Please specify a step (--step), a range (--range), or --all (or --status).")
        parser.print_help()
        sys.exit(1)

    print("Found %d step(s) to process in %s (prefix: %s)" %
          (len(steps_to_process), datadir, datafile))

    success_count = 0
    for s in steps_to_process:
        if options.extract:
            ok = extract_step(datadir, datafile, s)
        else:
            ok = archive_step(datadir, datafile, s, clean=options.clean)
        if ok:
            success_count += 1

    print("Done: %d / %d step(s) successfully processed." %
          (success_count, len(steps_to_process)))


if __name__ == '__main__':
    main()

